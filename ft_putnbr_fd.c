#include <unistd.h>

void	ft_putnbr_fd(int n, int fd)
{
	char	c;

	if (n < 0)
	{
		if (n / 10 != 0)
			ft_putnbr_fd(n / 10, fd);
		c = n % 10 * -1 + '0';
		if (n / 10 == 0)
			write(fd, "-", 1);
		write(fd, &c, 1);
	}
	else
	{
		if (n / 10 != 0)
			ft_putnbr_fd(n / 10, fd);
		c = n % 10 + '0';
		write(fd, &c, 1);
	}
}
